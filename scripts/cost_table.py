"""Per-question cost of each long-form method on TEST, G1 (EXPERIMENT_PLAN.md §6, RQ2), from logged counts only.

Pipeline stages logged by run_longform.py (summary.json -> cost.llm_by_stage) are attributed to methods:
  standard RAG = 1_generate;  CF = + 2_decompose (+ MiniCheck pairs);  C = CF + 3_closed_book_truth;
  A = C + 4_revise (+ NLI pairs, re-retrieval queries, re-scoring pairs).
Baselines (CoVe, RARR, FLARE) use their own summaries. SelfCheckGPT = CF's stages + 5 sampled generations per question
(prompt tokens = 5 x the RAG prompt; completion tokens of the samples were NOT logged) + 5 NLI pairs per claim.
Token counts are recorded for cached calls too, so they equal the cost of a cold run. Wall-clock is NOT reported
(stage seconds include cache hits). Writes results/<split>/cost_table.md. Usage: python scripts/cost_table.py [--split test]"""
import argparse
import glob
import json
from pathlib import Path

GEN = "Qwen2.5-7B-Instruct"


def one(p: str) -> Path:
    c = [Path(x) for x in glob.glob(p)]
    if len(c) != 1:
        raise SystemExit(f"expected one match for {p}: {c}")
    return c[0]


def default_run(split: str, ds: str) -> Path:
    for r in glob.glob(f"results/{split}/{ds}/longform__{GEN}__*/"):
        cfg = json.loads((Path(r) / "summary.json").read_text())["config"]
        if (cfg.get("k") == 5 and cfg.get("tau_s") == 0.5 and cfg.get("retriever") == "bm25" and cfg.get("verifier") == "MiniCheck-Flan-T5-Large"
                and not ({"triage", "decompose", "ablation_prompts", "limit"} & set(cfg))):
            return Path(r)
    raise SystemExit("no default run")


def stages(s: dict, names: list[str]) -> tuple[float, float, float]:
    st = s["cost"]["llm_by_stage"]
    calls = sum(st[n]["calls"] for n in names if n in st)
    pt = sum(st[n]["prompt_tokens"] for n in names if n in st)
    ct = sum(st[n]["completion_tokens"] for n in names if n in st)
    return calls, pt, ct


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="test")
    a = ap.parse_args()
    md = ["# Per-question cost, long-form TEST, G1 (generated by `scripts/cost_table.py`; logged counts only)\n",
          "LLM calls, prompt and completion tokens of the generator; retrieval queries; verifier pairs (MiniCheck / NLI). "
          "SelfCheckGPT: completion tokens of the 5 samples were not logged (marked '+?').\n"]
    for ds in ("bio", "asqa"):
        run = default_run(a.split, ds)
        s = json.loads((run / "summary.json").read_text())
        n = s["n"]
        vp = s["cost"]["verifier_pairs"]
        n_claims = s["claims_per_response_mean"] * n
        rows = []
        c, p, t = stages(s, ["1_generate"]); rows.append(("standard RAG", c, p, t, n, 0, 0))
        c, p, t = stages(s, ["1_generate", "2_decompose"]); base_mc = vp["nli"]  # MiniCheck pairs before repair = NLI pairs
        rows.append(("CF (filter only)", c, p, t, n, base_mc, 0))
        c2, p2, t2 = stages(s, ["1_generate", "2_decompose", "3_closed_book_truth"]); rows.append(("C (two-signal)", c2, p2, t2, n, base_mc, 0))
        c3, p3, t3 = stages(s, ["1_generate", "2_decompose", "3_closed_book_truth", "4_revise"])
        rows.append(("A (triage + repair)", c3, p3, t3, s["cost"]["retrieval_queries"], vp["minicheck"], vp["nli"]))
        g = s["cost"]["llm_by_stage"]["1_generate"]
        rows.append(("SelfCheckGPT-NLI", c + 5 * n, p + 5 * g["prompt_tokens"], None, n, base_mc, 5 * n_claims))
        for name, pat in (("CoVe (closed-book)", "cove-closed_book"), ("CoVe (retrieval-verified)", "cove-rag_verify"), ("RARR-style", "rarr"), ("FLARE-direct", "flare")):
            b = json.loads((one(f"results/{a.split}/{ds}/{pat}__{GEN}__*/") / "summary.json").read_text())
            st = b["cost"]["llm_by_stage"]
            rows.append((name, sum(v["calls"] for v in st.values()), sum(v["prompt_tokens"] for v in st.values()),
                         sum(v["completion_tokens"] for v in st.values()), b["cost"].get("retrieval_queries", 0), 0, 0))
        md.append(f"## {'Biographies' if ds == 'bio' else 'ASQA'} (n = {n}; run `{run.name}`)\n")
        md.append("| Method | LLM calls / q | prompt tokens / q | completion tokens / q | retrieval queries / q | MiniCheck pairs / q | NLI pairs / q |")
        md.append("|---|---|---|---|---|---|---|")
        for name, c, p, t, r, mc, nl in rows:
            md.append(f"| {name} | {c / n:.1f} | {p / n:,.0f} | {'+?' if t is None else f'{t / n:,.0f}'} | {r / n:.1f} | {mc / n:.1f} | {nl / n:.1f} |")
        md.append("")
    Path(f"results/{a.split}/cost_table.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
