"""Phase 6 ablation / sensitivity table on TEST (EXPERIMENT_PLAN.md §8, D6) — EXPLORATORY.

For every judged long-form run of a Qwen generator (default G1 run, its ablation configurations, and the 3B / 14B
size runs): CF, C and A (and, on the default G1 run, A with only one repair branch) at each target, mean ± std over
100 partitions; A − CF and C − CF at 0.90 by the same partition-0 paired bootstrap as the confirmatory test.
Writes results/<split>/ablations.json and results/<split>/tables_ablations.md.
Usage: python scripts/ablation_table.py [--split test]"""
from __future__ import annotations

import argparse
import glob
import json
from pathlib import Path

from hallu import analysis as A
from hallu import metrics as M
from hallu.pipeline import RERETRIEVE, REVISE, final_claims
from hallu.runutil import git_commit
from hallu.store import read_jsonl, text_key

JT = "phi-4-FP8-dynamic"
TARGETS = [0.80, 0.85, 0.90, 0.95]
DEFAULTS = {"k": 5, "tau_s": 0.5, "retriever": "bm25", "verifier": "MiniCheck-Flan-T5-Large", "triage": "two_axis", "decompose": "llm",
            "model": "Qwen/Qwen2.5-7B-Instruct"}


def label(cfg: dict) -> str:
    diff = [f"{k}={cfg.get(k, v)}" for k, v in DEFAULTS.items() if cfg.get(k, v) != v]
    return "default (G1)" if not diff else ", ".join(diff).replace("|", "given")  # '|' would break markdown tables


def order(name: str) -> tuple:
    """Table order: default first, then ablations grouped by option, size runs last."""
    groups = ["default", "triage", "tau_s", "k=", "decompose", "verifier", "retriever", "model"]
    return (next((i for i, g in enumerate(groups) if name.startswith(g)), len(groups)), name)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="test")
    a = ap.parse_args()
    out = {"label": "EXPLORATORY (§8 ablations / sensitivity)", "git_commit": git_commit(), "judge_tag": JT, "runs": {}}
    md = [f"# Ablations and sensitivity ({a.split}) — generated by `scripts/ablation_table.py`; EXPLORATORY\n",
          "Supported claims / answer at target 0.90 (mean ± std over 100 partitions; realised P(all kept supported) in brackets); "
          "Δ = paired bootstrap on partition 0 (10,000, seed 0).\n"]
    for ds in ("bio", "asqa"):
        md.append(f"## {'Biographies' if ds == 'bio' else 'ASQA'}\n")
        md.append("| Configuration | n claims / answer | CF | C | A | A − CF (95% CI, p) | C − CF (95% CI, p) | run |")
        md.append("|---|---|---|---|---|---|---|---|")
        runs = []
        for r in glob.glob(f"results/{a.split}/{ds}/longform__Qwen2.5-*__*/"):
            r = Path(r)
            if not ((r / f"judge__{JT}.jsonl").exists() and (r / "summary.json").exists()):
                continue
            c = json.loads((r / "summary.json").read_text())["config"]
            if c.get("prompts") == "v2" and "limit" not in c:
                runs.append((order(label(c)), r))
        for _, run in sorted(runs):
            summ = json.loads((run / "summary.json").read_text())
            cfg = summ["config"]
            rows = read_jsonl(run / "items.jsonl")
            labels = {r["id"]: r["label"] for r in read_jsonl(run / f"judge__{JT}.jsonl")}
            lab = lambda iid, t: labels[text_key(iid, t)]  # noqa: E731
            methods = {"CF": [[(c["s"], lab(r["id"], c["text"])) for c in r["claims"]] for r in rows],
                       "C": [[(c["score_c"], lab(r["id"], c["text"])) for c in r["claims"]] for r in rows],
                       "A": [[(f["score"], lab(r["id"], f["text"])) for f in final_claims(r["claims"])] for r in rows]}
            name = label(cfg)
            if name == "default (G1)":
                methods["A, revision only (§8.3)"] = [[(f["score"], lab(r["id"], f["text"])) for f in final_claims(r["claims"], branches=(REVISE,))] for r in rows]
                methods["A, re-retrieval only (§8.2)"] = [[(f["score"], lab(r["id"], f["text"])) for f in final_claims(r["claims"], branches=(RERETRIEVE,))] for r in rows]
            res = {str(t): {m: A.evaluate(v, 1 - t, 100) for m, v in methods.items()} for t in TARGETS}
            res["unfiltered"] = {m: A.evaluate(v, None, 100) for m, v in methods.items() if m in ("CF", "A")}
            tests = {}
            for m in [x for x in methods if x != "CF"]:
                r1, r0 = A.evaluate_once(methods[m], 0.10, seed=0), A.evaluate_once(methods["CF"], 0.10, seed=0)
                tests[f"{m} vs CF"] = M.paired_bootstrap(r1["supported_per_response"], r0["supported_per_response"], 10_000, seed=0)
            out["runs"][str(run)] = {"dataset": ds, "configuration": name, "config": cfg, "actions": summ.get("actions"),
                                     "claims_per_response_mean": summ.get("claims_per_response_mean"), "results": res, "tests_at_0.90": tests}

            def cell(m: str) -> str:
                e = res["0.9"][m]
                return f"{e['supported_claims_per_response']['mean']:.3f} ± {e['supported_claims_per_response']['std']:.3f} [{e['all_retained_correct_rate']['mean']:.3f}]"

            def tcell(key: str) -> str:
                b = tests[key]
                return f"{b['diff']:+.3f} [{b['ci_low']:+.3f}, {b['ci_high']:+.3f}], p={b['p_value']:.4f}"

            md.append(f"| {name} | {summ.get('claims_per_response_mean', float('nan')):.2f} | {cell('CF')} | {cell('C')} | {cell('A')} "
                      f"| {tcell('A vs CF')} | {tcell('C vs CF')} | `{run.name}` |")
            for extra in ("A, revision only (§8.3)", "A, re-retrieval only (§8.2)"):
                if extra in methods:
                    md.append(f"| {name}: {extra} | | | | {cell(extra)} | {tcell(extra + ' vs CF')} | | |")
            print(f"{ds} {name:40s} CF {cell('CF')} | C {cell('C')} | A {cell('A')}", flush=True)
        md.append("")
    Path(f"results/{a.split}/ablations.json").write_text(json.dumps(out, indent=1, default=float))
    Path(f"results/{a.split}/tables_ablations.md").write_text("\n".join(md))
    print("wrote", f"results/{a.split}/ablations.json", f"results/{a.split}/tables_ablations.md")


if __name__ == "__main__":
    main()
