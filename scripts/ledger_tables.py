"""Generate the Phase 5 TEST result tables (markdown) from the analysis JSON files - no hand transcription.
Writes results/<split>/tables_phase5.md. Usage: python scripts/ledger_tables.py [--split test]
Every cell is mean ± std over the 100 seeded calibration/evaluation partitions unless stated otherwise."""
import argparse
import glob
import json
from pathlib import Path

JT = "phi-4-FP8-dynamic"
GENS = ["Qwen2.5-7B-Instruct", "Mistral-7B-Instruct-v0.3", "Falcon3-7B-Instruct"]
LF = [("bio", "Biographies"), ("asqa", "ASQA")]
SF = [("popqa", "PopQA"), ("nq", "NQ"), ("triviaqa", "TriviaQA"), ("hotpotqa", "HotpotQA"), ("2wiki", "2Wiki")]
TARGETS = ["0.8", "0.85", "0.9", "0.95"]


def ms(d: dict, k: str, nd: int = 3) -> str:
    return f"{d[k]['mean']:.{nd}f} ± {d[k]['std']:.{nd}f}"


def one(pattern: str) -> Path:
    c = [Path(p) for p in glob.glob(pattern)]
    if len(c) != 1:
        raise SystemExit(f"expected exactly 1 match for {pattern}, got {c}")
    return c[0]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="test")
    a = ap.parse_args()
    S = a.split
    out: list[str] = [f"# Phase 5 tables ({S}) — generated by `scripts/ledger_tables.py` from analysis JSON; do not edit\n"]

    out.append("## T1. Long-form, G1 = Qwen2.5-7B-Instruct: all methods (comparison file per dataset)\n")
    for ds, name in LF:
        f = one(f"results/{S}/{ds}/comparison__*__v2__{JT}.json")
        rows = json.loads(f.read_text())["rows"]
        out.append(f"### {name} — source `{f}`\n")
        out.append("| Method | supported claims / answer | claims kept / answer | non-empty rate | factual precision (micro) | P(all kept claims supported) |")
        out.append("|---|---|---|---|---|---|")
        for m, r in rows.items():
            out.append(f"| {m} | {ms(r, 'supported_claims_per_response')} | {ms(r, 'claims_kept_per_response')} | {ms(r, 'non_empty_rate')} "
                       f"| {ms(r, 'factual_precision_micro')} | {ms(r, 'all_retained_correct_rate')} |")
        out.append("")

    out.append("## T2. Long-form, all generators: supported claims / answer at each conformal target (realised P(all kept supported) in brackets)\n")
    for ds, name in LF:
        out.append(f"### {name}\n")
        out.append("| Generator | Method | " + " | ".join(f"target {t}" for t in TARGETS) + " | source |")
        out.append("|---|---|" + "---|" * len(TARGETS) + "---|")
        for g in GENS:
            f = one(f"results/{S}/{ds}/longform__{g}__*/analysis__{JT}.json")
            an = json.loads(f.read_text())
            ref = an["unfiltered"]["standard RAG (all claims)"]
            out.append(f"| {g} | standard RAG, no filter | {ms(ref, 'supported_claims_per_response')} "
                       f"[{ref['all_retained_correct_rate']['mean']:.3f}] |" + " |" * (len(TARGETS) - 1) + f" `{f.parent.name}` |")
            for m in an["targets"][TARGETS[0]]:
                cells = []
                for t in TARGETS:
                    r = an["targets"][t][m]
                    cells.append(f"{ms(r, 'supported_claims_per_response')} [{r['all_retained_correct_rate']['mean']:.3f}]")
                out.append(f"| {g} | {m} | " + " | ".join(cells) + " | |")
        out.append("")

    out.append("## T3. A (repair + filter) vs CF (filter only) at target 0.90, partition 0, paired bootstrap 10,000; pilot R\n")
    out.append("H1/H2 (G1, Holm over 2) are the only confirmatory tests; G2/G3 rows are secondary (no multiplicity correction, "
               "report as such). p = 0.0 means no resample crossed 0, i.e. p < 1e-4.\n")
    out.append("| Dataset | Generator | n eval | Δ supported / answer | 95% CI | p | Δ precision | one-sided 95% lower | guard (≥ −0.02) | R | R_net | R_kept |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for ds, name in LF:
        for g in GENS:
            an = json.loads(one(f"results/{S}/{ds}/longform__{g}__*/analysis__{JT}.json").read_text())
            t, pi = an["A_vs_CF_at_0.90"], an["pilot"]
            sp, pr = t["supported_per_response"], t["precision_micro_diff"]
            out.append(f"| {name} | {g} | {sp['n']} | {sp['diff']:+.3f} | [{sp['ci_low']:+.3f}, {sp['ci_high']:+.3f}] | {sp['p_value']:.4f} "
                       f"| {pr['diff']:+.3f} | {pr['one_sided_95_lower']:+.3f} | {t['guard_holds']} | {pi['R']:.3f} | {pi['R_net']:.4f} | {pi['R_kept']:.4f} |")
    out.append("")
    conf = json.loads(Path(f"results/{S}/confirmatory.json").read_text())
    out.append(f"Confirmatory (`results/{S}/confirmatory.json`, α = {conf['alpha']}, {conf['correction']}): " + "; ".join(
        f"{h} ({r['dataset']}) Δ = {r['diff_supported_per_response']:+.3f}, CI [{r['ci95'][0]:+.3f}, {r['ci95'][1]:+.3f}], "
        f"p = {r['p_value']:.4f}, Holm reject = {r['holm_reject']}, guard = {r['guard_holds']} → SUPPORTED = {r['SUPPORTED']}"
        for h, r in conf["results"].items()) + "\n")

    out.append("## T4. Short-form (n = 1,000 per set): accuracy, AURC (lower = better), selective accuracy at 50% coverage, ECE\n")
    out.append("| Set | Generator | RAG acc | A acc (no abstention) | AURC CF | AURC C | AURC A | sel-acc@50 CF | sel-acc@50 C | sel-acc@50 A | ECE CF | ECE C | ECE A | run |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for ds, name in SF:
        for g in GENS:
            f = one(f"results/{S}/{ds}/shortform__{g}__*/analysis.json")
            an = json.loads(f.read_text())
            M = an["methods"]
            cf, c, aa = M["CF (score s)"], M["C (two-signal)"], M["A (repair)"]
            out.append(f"| {name} | {g} | {an['standard_rag']['accuracy']:.3f} | {aa['accuracy_no_abstention']:.3f} "
                       f"| {cf['aurc']:.3f} | {c['aurc']:.3f} | {aa['aurc']:.3f} "
                       f"| {cf['selective_acc_cov50']:.3f} | {c['selective_acc_cov50']:.3f} | {aa['selective_acc_cov50']:.3f} "
                       f"| {cf['ece']:.3f} | {c['ece']:.3f} | {aa['ece']:.3f} | `{f.parent.name}` |")
    out.append("")
    ex_path = Path(f"results/{S}/exploratory_tests.json")
    if ex_path.exists():
        ex = json.loads(ex_path.read_text())
        out.append("## T5. EXPLORATORY (unadjusted): long-form pairwise comparisons at target 0.90 "
                   f"(`{ex_path}`, `scripts/exploratory_tests.py`)\n")
        out.append("Bootstrap on partition 0 (10,000, seed 0); 'partitions' = difference of means on each of the 100 partitions. "
                   "p = 0.0000 means p < 1e-4.\n")
        out.append("| Dataset / generator | Comparison | Δ supported / answer | 95% CI | p | Δ precision (one-sided 95% lb) | partitions: mean ± std | share > 0 |")
        out.append("|---|---|---|---|---|---|---|---|")
        for key, v in ex["longform"].items():
            for pair, r in v["results"]["0.9"].items():
                b, pr, pp = r["supported_per_response"], r["precision_micro"], r["partitions"]
                out.append(f"| {key} | {pair} | {b['diff']:+.3f} | [{b['ci_low']:+.3f}, {b['ci_high']:+.3f}] | {b['p_value']:.4f} "
                           f"| {pr['diff']:+.3f} ({pr['one_sided_95_lower']:+.3f}) | {pp['mean_diff']:+.3f} ± {pp['std_diff']:.3f} | {pp['share_positive']:.2f} |")
        out.append("")
        out.append("## T6. EXPLORATORY (unadjusted): short-form — A vs standard RAG accuracy (exact McNemar) and AURC(C) − AURC(CF) "
                   "(paired bootstrap 10,000, seed 0; negative = C better)\n")
        out.append("| Set / generator | acc RAG | acc A | A right & RAG wrong | A wrong & RAG right | McNemar p | ΔAURC C − CF | 95% CI | p |")
        out.append("|---|---|---|---|---|---|---|---|---|")
        for key, v in ex["shortform"].items():
            mc, au = v["A_vs_RAG_accuracy_mcnemar"], v["AURC_C_minus_CF"]
            out.append(f"| {key} | {v['acc_RAG']:.3f} | {v['acc_A']:.3f} | {mc['n10']} | {mc['n01']} | {mc['p_value']:.4f} "
                       f"| {au['diff']:+.3f} | [{au['ci_low']:+.3f}, {au['ci_high']:+.3f}] | {au['p_value']:.4f} |")
        out.append("")
    p = Path(f"results/{S}/tables_phase5.md")
    p.write_text("\n".join(out))
    print("wrote", p, len(out), "lines")


if __name__ == "__main__":
    main()
